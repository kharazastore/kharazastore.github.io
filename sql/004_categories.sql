-- 004_categories.sql: جدول فئات المنتجات
create table if not exists categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

alter table categories enable row level security;

drop policy if exists "staff categories" on categories;
create policy "staff categories" on categories
  for all to authenticated using (true) with check (true);

drop policy if exists "public read categories" on categories;
create policy "public read categories" on categories
  for select to anon using (true);

insert into categories (name) values
  ('موبايلات'), ('كفرات'), ('حافظات'), ('زجاج حماية'), ('شواحن'),
  ('كابلات'), ('سماعات'), ('باور بانك'), ('إكسسوارات'), ('قطع غيار'), ('أخرى')
on conflict (name) do nothing;
