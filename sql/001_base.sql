-- 001_base.sql: الفروع والملفات الشخصية للموظفين وأدوارهم
-- شغّله مرة واحدة في Supabase SQL Editor.

-- 1) الفروع
create table if not exists branches (
  id bigint generated by default as identity primary key,
  name text not null,
  address text,
  phone text,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

-- 2) الملفات الشخصية: كل موظف مربوط بحساب Auth ودور واحد وفرع (للمدير الفرع null = كل الفروع)
create table if not exists profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  role text not null check (role in ('manager', 'technician', 'cashier')),
  branch_id bigint references branches(id),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  constraint branch_required_for_staff check (role = 'manager' or branch_id is not null)
);

-- 3) دوال مساعدة: security definer عشان سياسات RLS مايحصلش فيها recursion
create or replace function my_role() returns text
language sql stable security definer set search_path = public as $$
  select role from profiles where id = auth.uid() and active
$$;

create or replace function my_branch() returns bigint
language sql stable security definer set search_path = public as $$
  select branch_id from profiles where id = auth.uid() and active
$$;

-- 4) تفعيل RLS
alter table branches enable row level security;
alter table profiles enable row level security;

-- 5) سياسات الفروع: أي موظف مسجل يقراها، والمدير بس يعدّلها
drop policy if exists "branches read" on branches;
drop policy if exists "branches manage" on branches;
create policy "branches read" on branches
  for select to authenticated using (true);
create policy "branches manage" on branches
  for all to authenticated
  using (my_role() = 'manager') with check (my_role() = 'manager');

-- 6) سياسات الملفات: الموظف يقرا ملفه بس، والمدير يقرا ويدير الكل
drop policy if exists "profiles read own" on profiles;
drop policy if exists "profiles manager" on profiles;
create policy "profiles read own" on profiles
  for select to authenticated using (id = auth.uid());
create policy "profiles manager" on profiles
  for all to authenticated
  using (my_role() = 'manager') with check (my_role() = 'manager');

-- 7) بيانات الفرعين (غيّر الأسماء والعناوين)
insert into branches (name, address, phone)
select 'الفرع الأول', '', ''
where not exists (select 1 from branches where name = 'الفرع الأول');

insert into branches (name, address, phone)
select 'الفرع الثاني', '', ''
where not exists (select 1 from branches where name = 'الفرع الثاني');

